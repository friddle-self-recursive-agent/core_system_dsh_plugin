#!/usr/bin/env node
// build-client.mjs —— 组装 dsh client bundle（lazy-CJS 工厂形，dsh-client-modules 契约）：
//   window.__ModuleLoader__.load({id:<包名>, factory: require => {...返回 exports}})
// 零外部构建依赖：源文件即普通 script 顺序拼接进同一闭包（data → app → monitor → entry）。
// dist/client.js 随源入库——dsh 启动即读该文件（缺件=激活期响亮失败），构建必须先于 web 启动。
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const PKG_ID = 'dsh-plugin-core-system'
const parts = ['console-shell.js', 'console-data.js', 'console-app.js', 'conn-monitor.js', 'entry.js']
const css = readFileSync(join(root, 'client/console.css'), 'utf8')

const body = [
  `var module = { exports: {} }; var exports = module.exports;`,
  `var React = require('react'); // 平台种子模块（dsh client 各 bundle 同款引用，无需 inject 边）`,
  `var CC_CSS = ${JSON.stringify(css)};`,
  `var __CC = { MOCK: {} };`,
  ...parts.map((p) => readFileSync(join(root, 'client', p), 'utf8')),
  `return module.exports;`,
].join('\n')

const banner =
  `/*! ${PKG_ID} client face — console v2 E1（generated by build-client.mjs；勿手改，源在 client/） */\n` +
  `window.__ModuleLoader__.load({ id: '${PKG_ID}', factory: function (require) {\n`
const out = banner + body + '\n}});\n'

mkdirSync(join(root, 'dist'), { recursive: true })
writeFileSync(join(root, 'dist/client.js'), out)
// 语法自检：node --check 等价（new Function 不执行，仅解析）
try {
  new Function(`window={__ModuleLoader__:{load(){}}}; ${out}`)
} catch (e) {
  console.error('build-client: bundle 语法不合法:', e.message)
  process.exit(1)
}
console.log(`build-client: dist/client.js written (${out.length} bytes)`)
